# Private scratch files for lifecycle checks. Source after setting ROOT_DIR.
umask 077
readonly FINTECH_TMP_DIR="$(mktemp -d "${TMPDIR:-/tmp}/fintech-platform.XXXXXX")"

fintech_cleanup_private_tmp() {
  if [[ -d "${FINTECH_TMP_DIR}" ]]; then
    rm -rf "${FINTECH_TMP_DIR}"
  fi
}

fintech_json_array_file() {
  python3 - "$1" "$2" <<'PY'
import json
import sys

with open(sys.argv[1], encoding="utf-8") as source:
    data = json.load(source)
with open(sys.argv[2], "w", encoding="utf-8") as destination:
    json.dump([data], destination)
PY
}

fintech_keycloak_admin_password_file() {
  local env_file="$1"
  local password_file="${FINTECH_TMP_DIR}/kc-admin-password"
  if [[ ! -f "$password_file" ]]; then
    local password
    password="$(grep -E '^KEYCLOAK_ADMIN_PASSWORD=' "$env_file" | head -1 | cut -d= -f2- | tr -d '"')"
    printf '%s' "$password" > "$password_file"
    unset password
  fi
  printf '%s' "$password_file"
}

# The synthetic realm users' password, read from .env (generated by bootstrap.sh).
# Never hardcoded: the committed realm resolves it at import via ${SEED_USER_PASSWORD}.
fintech_seed_user_password() {
  local env_file="$1"
  local value
  value="$(grep -E '^SEED_USER_PASSWORD=' "$env_file" | head -1 | cut -d= -f2- | tr -d '"')"
  if [[ -z "$value" || "$value" == "CHANGE_ME" ]]; then
    echo "SEED_USER_PASSWORD is missing from ${env_file}; run ./scripts/bootstrap.sh" >&2
    return 1
  fi
  printf '%s' "$value"
}
